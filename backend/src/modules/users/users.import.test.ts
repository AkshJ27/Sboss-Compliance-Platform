import { describe, it, expect } from 'vitest';
import { parseUserSheet, planUserImport } from './users.import.parser';
import type { ExistingUser } from './users.import.parser';

const header = ['First Name', 'Last Name', 'Email', 'Created On', 'Status', 'Manager', 'Entity', 'Department', 'Location', 'Compliance Role', 'Email Alerts', 'Lock Status', 'Mobile No.', 'Daily Escalation Status', 'IP Based Authentication', 'User ID', 'Vertical*', 'Last Login Date'];
const row = (first: string, last: string, email: string, o: Partial<Record<'status' | 'manager' | 'role' | 'alerts' | 'id', string>> = {}) =>
    [first, last, email, '15-Mar-2024 22:36', o.status ?? 'Active', o.manager ?? '', 'SBOSS', 'Vendors', 'Maharashtra', o.role ?? 'Owner/Manager', o.alerts ?? 'Yes', 'Open', '', 'No', 'No', o.id ?? '100', 'SBOSS', ''];
const sheet = (rows: unknown[][]) => [['Organisation:', 'X', 'Report Name: ', 'List of Users'], ['Generated By:', 'A'], [], header, ...rows];

describe('users upload', () => {
    it("reads Complinity's export, skipping the notes under the list", () => {
        const out = parseUserSheet(sheet([
            row('Akshay', 'Chikodikar', 'CS@sboss.net.in', { role: 'Administrator', id: '18283' }),
            row('Amita', 'Govekar', 'hr13@sboss.net.in', { status: 'Inactive', alerts: 'No' }),
            [],
            ['HR compliance-HO-Amita-Perform', 'Approver-Vikash'],
        ]));
        expect(out.fileErrors).toEqual([]);
        expect(out.errors).toEqual([]);
        expect(out.rows).toHaveLength(2);
        expect(out.rows[0]).toMatchObject({ row: 5, name: 'Akshay Chikodikar', email: 'cs@sboss.net.in', role: 'ORG_ADMIN', isActive: true, employeeCode: '18283' });
        expect(out.rows[1]).toMatchObject({ role: 'MEMBER', isActive: false, emailAlerts: false });
        expect(out.warnings.some((w) => w.includes('Row(s) 8 have no email'))).toBe(true);
        expect(out.warnings.some((w) => w.includes('Entity'))).toBe(true);
    });

    it('reports bad values and repeated emails', () => {
        const out = parseUserSheet(sheet([
            row('A', '', 'not-an-email', { role: 'Wizard' }),
            row('Ravi', 'K', 'ravi@x.in'),
            row('Ravi', 'Kumar', 'RAVI@x.in'),
        ]));
        const msgs = out.errors.map((e) => `${e.row} ${e.field}: ${e.message}`);
        expect(msgs).toContain('5 First Name: Enter the name');
        expect(msgs).toContain('5 Email: Not a valid email address');
        expect(msgs).toContain('5 Compliance Role: Use Administrator, Owner/Manager or Viewer, not "Wizard"');
        expect(msgs).toContain('7 Email: The same email is already on row 6');
    });

    it('links managers by name, within the file or the company, and keeps you an admin', () => {
        const rows = parseUserSheet(sheet([
            row('Amita', 'Govekar', 'hr13@sboss.net.in', { manager: 'Shashi Bhushan Chaudhary' }),
            row('Vikash', 'S', 'v@sboss.net.in', { manager: 'amita govekar' }),
            row('Neha', 'P', 'neha@sboss.net.in', { manager: 'Old Boss' }),
            row('Me', 'Admin', 'me@sboss.net.in', { role: 'Owner/Manager' }),
        ])).rows;
        const existing: ExistingUser[] = [
            { id: 'u-shashi', orgId: 'o', email: 'shashi@sboss.net.in', name: 'Shashi Bhushan Chaudhary', role: 'ORG_ADMIN', isActive: true, managerId: null, defaultApproverId: null },
            { id: 'u-me', orgId: 'o', email: 'me@sboss.net.in', name: 'Me Admin', role: 'ORG_ADMIN', isActive: true, managerId: null, defaultApproverId: null },
            { id: 'u-other', orgId: 'x', email: 'v@sboss.net.in', name: 'Elsewhere', role: 'MEMBER', isActive: true, managerId: null, defaultApproverId: null },
        ];
        const plan = planUserImport(rows, existing, 'o', 'u-me');
        expect(plan.errors.map((e) => e.message)).toEqual([
            'v@sboss.net.in belongs to another company on this platform',
            'This is you. You cannot deactivate yourself or remove your own admin role.',
        ]);
        expect(plan.planned.map((p) => [p.row.email, p.managerRef])).toEqual([
            ['hr13@sboss.net.in', 'u-shashi'],
            ['neha@sboss.net.in', null],
        ]);
        expect(plan.warnings[0]).toContain('Manager "Old Boss"');
    });

    it('points at a new user in the same file by email until they are saved', () => {
        const rows = parseUserSheet(sheet([
            row('Amita', 'Govekar', 'hr13@sboss.net.in'),
            row('Vikash', 'S', 'v@sboss.net.in', { manager: 'Amita Govekar' }),
        ])).rows;
        const plan = planUserImport(rows, [], 'o', 'u-me');
        expect(plan.planned[1].managerRef).toBe('email:hr13@sboss.net.in');
        expect(plan.planned.every((p) => p.existingId === null)).toBe(true);
    });

    it("sets each person's default approver from an Approver column", () => {
        const grid = [
            ['First Name', 'Last Name', 'Email', 'Status', 'Compliance Role', 'Approver'],
            ['Shashi Bhushan', 'Chaudhary', 'fh1@sboss.net.in', 'Active', 'Owner/Manager', ''],
            ['Akshay', 'C', 'cs@sboss.net.in', 'Active', 'Administrator', 'Shashi Bhushan Chaudhary'],
            ['Indra', 'K', 'indra@sboss.net.in', 'Active', 'Owner/Manager', 'fh2@sboss.net.in'],
            ['Vipin', 'R', 'vipin@sboss.net.in', 'Active', 'Owner/Manager', 'Nobody Here'],
        ];
        const parsed = parseUserSheet(grid);
        expect(parsed.errors).toEqual([]);
        const existing: ExistingUser[] = [
            { id: 'u-madhu', orgId: 'o', email: 'fh2@sboss.net.in', name: 'Madhubabu Indupuri', role: 'MEMBER', isActive: true, managerId: null, defaultApproverId: null },
        ];
        const plan = planUserImport(parsed.rows, existing, 'o', 'u-me');
        expect(plan.errors).toEqual([]);
        expect(plan.planned.map((p) => [p.row.email, p.approverRef])).toEqual([
            ['fh1@sboss.net.in', null],
            ['cs@sboss.net.in', 'email:fh1@sboss.net.in'],
            ['indra@sboss.net.in', 'u-madhu'],
            ['vipin@sboss.net.in', null],
        ]);
        expect(plan.warnings.some((w) => w.startsWith('Approver "Nobody Here"'))).toBe(true);
    });

    it('refuses a viewer as approver', () => {
        const grid = [
            ['Name', 'Email', 'Compliance Role', 'Approver'],
            ['View Only', 'v@x.in', 'Viewer', ''],
            ['Ravi K', 'r@x.in', 'Owner/Manager', 'View Only'],
        ];
        const plan = planUserImport(parseUserSheet(grid).rows, [], 'o', 'u-me');
        expect(plan.errors.map((e) => `${e.row} ${e.field}: ${e.message}`)).toEqual(['3 Approver: View Only is a viewer, so cannot approve']);
    });
});
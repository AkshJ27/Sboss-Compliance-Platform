import { describe, it, expect } from 'vitest';
import { LEGAL_COLUMNS, parseLegalDate, parseLegalSheet, planLegalImport } from './legal.import.parser';
import type { LegalLookups } from './legal.import.parser';
import { planLegalNotices } from './legal.notify';

const header = LEGAL_COLUMNS.map((c) => c.header);
const row = (o: Record<string, string> = {}) => {
    const base: Record<string, string> = {
        lawCategory: 'Corporate Laws', act: 'Companies Act, 2013', rule: 'NA', region: 'Central', ministry: 'Ministry of Corporate Affairs',
        notificationDate: '03-Nov-26', effectiveDate: '04-Nov-26', referenceNumber: 'G.S.R. 968(E)', title: 'MCA issues amendment rules',
        description: 'What changed', complianceImpact: 'Yes', change: 'No', addition: 'Yes', deletion: 'No', schedule: 'No',
        impactedCompliance: '', publishedDate: '06-Nov-26',
    };
    const v = { ...base, ...o };
    return LEGAL_COLUMNS.map((c) => v[c.key] ?? '');
};
// The register has title lines above the headings, like the real export
const sheet = (rows: string[][]) => [
    ['Organisation:', 'SBOSS', 'Report Name: ', 'Legal Updates Register'],
    ['Generated By:', 'Akshay'],
    [],
    header,
    ...rows,
];

describe('legal updates register', () => {
    it('reads two-digit years and the usual date forms', () => {
        expect(parseLegalDate('11-Nov-26')).toBe('2026-11-11');
        expect(parseLegalDate('01-Dec-2025')).toBe('2025-12-01');
        expect(parseLegalDate('2026-03-31')).toBe('2026-03-31');
        expect(parseLegalDate('31-Feb-26')).toBeNull();
    });

    it('finds the heading row under the title lines and reads a row', () => {
        const out = parseLegalSheet(sheet([row(), row({ region: 'andhra pradesh', rule: 'Shops Rules', complianceImpact: '' })]));
        expect(out.fileErrors).toEqual([]);
        expect(out.errors).toEqual([]);
        expect(out.rows[0]).toMatchObject({
            row: 5, jurisdiction: 'CENTRAL', state: null, rule: null, notificationDate: '2026-11-03',
            publishedDate: '2026-11-06', complianceImpact: true, isAddition: true, impactedCompliance: null,
        });
        expect(out.rows[1]).toMatchObject({ jurisdiction: 'STATE', state: 'Andhra Pradesh', rule: 'Shops Rules', complianceImpact: false });
    });

    it('reports bad values with their row', () => {
        const out = parseLegalSheet(sheet([row({ region: 'Atlantis', notificationDate: 'soon', change: 'maybe', title: '' })]));
        const msgs = out.errors.map((e) => `${e.row} ${e.field}: ${e.message}`);
        expect(msgs).toContain('5 Title: Required');
        expect(msgs).toContain('5 Notification Date: Use a date like 11-Nov-2026');
        expect(msgs).toContain('5 Change: Use Yes or No');
        expect(msgs.some((m) => m.startsWith('5 Central/State: Use Central'))).toBe(true);
    });

    it('plans new Acts and Rules, and skips repeats', () => {
        const rows = parseLegalSheet(sheet([
            row(),
            row(), // the same again
            row({ act: 'Reserve Bank of India Act, 1934', rule: 'KYC Direction, 2016', title: 'RBI update' }),
        ])).rows;
        const lk: LegalLookups = {
            categories: new Map([['corporate laws', 'c1']]),
            acts: new Map([['companies act, 2013|CENTRAL|', { id: 'a1', lawCategoryId: 'c1' }]]),
            rules: new Map(),
            existing: new Set(),
        };
        const plan = planLegalImport(rows, lk);
        expect(plan.toCreate.map((c) => c.actRef)).toEqual(['a1', 'new:reserve bank of india act, 1934|CENTRAL|']);
        expect(plan.duplicates).toBe(1);
        expect(plan.newActs.size).toBe(1);
        expect(plan.newRules.size).toBe(1);
        expect(plan.toCreate[1].ruleRef).toBe('new:new:reserve bank of india act, 1934|CENTRAL||kyc direction, 2016');
    });
});

describe('legal update notices', () => {
    const u = (id: string, actId: string, publishedDate: string) => ({ id, actId, actName: `Act ${actId}`, title: `Update ${id}`, publishedDate });

    it('sends one notice per person, emailing only those who asked', () => {
        const notices = planLegalNotices(
            [u('1', 'a', '2026-11-16'), u('2', 'a', '2026-11-15'), u('3', 'b', '2026-11-16')],
            [
                { userId: 'p1', orgId: 'o', actId: 'a', emailAlerts: false },
                { userId: 'p1', orgId: 'o', actId: 'b', emailAlerts: true },
                { userId: 'p2', orgId: 'o', actId: 'b', emailAlerts: false },
                { userId: 'p3', orgId: 'o', actId: 'z', emailAlerts: true },
            ],
            '2026-11-17',
        );
        expect(notices.map((n) => [n.userId, n.email])).toEqual([['p1', true], ['p2', false]]);
        expect(notices[0].title).toBe('3 new legal updates for the Acts you follow');
        expect(notices[1].title).toBe('Legal update: Update 3');
    });

    it('stays quiet about old updates', () => {
        expect(planLegalNotices([u('1', 'a', '2026-10-01')], [{ userId: 'p1', orgId: 'o', actId: 'a', emailAlerts: true }], '2026-11-17')).toEqual([]);
    });
});
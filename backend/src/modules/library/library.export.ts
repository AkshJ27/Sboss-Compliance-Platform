import ExcelJS from 'exceljs';
import { HttpError } from '../../lib/errors';
import { prisma } from '../../lib/prisma';
import { toDateOnly, todayInIndia } from '../../lib/dates';
import type { AuthUser } from '../../middleware/auth';
import { complianceWhere } from './library.service';
import { dueRuleText } from './due-text';

const EXPORT_LIMIT = 20_000;
const words = (s: string) => s.toLowerCase().replace(/_/g, ' ').replace(/^\w/, (c) => c.toUpperCase());
// Text starting with = + - @ would run as a formula in Excel
const safe = (v: string | null | undefined) => (v && /^[=+\-@\t\r]/.test(v) ? `'${v}` : (v ?? ''));

const COLUMNS: { header: string; width: number }[] = [
    { header: 'Compliance ID', width: 14 },
    { header: 'Compliance Name', width: 50 },
    { header: 'Compliance Description', width: 60 },
    { header: 'Act Name', width: 40 },
    { header: 'Rule Name', width: 35 },
    { header: 'State', width: 18 },
    { header: 'Law Category', width: 20 },
    { header: 'Statutory/Internal', width: 16 },
    { header: 'Compliance Nature', width: 18 },
    { header: 'Compliance Type', width: 18 },
    { header: 'Periodicity', width: 14 },
    { header: 'Due', width: 40 },
    { header: 'Financial/Calendar Year', width: 20 },
    { header: 'Form No', width: 16 },
    { header: 'Reference', width: 20 },
    { header: 'Risk', width: 10 },
    { header: 'Impact', width: 10 },
    { header: 'Attachment', width: 12 },
    { header: 'Penalty', width: 50 },
    { header: 'Imprisonment', width: 13 },
    { header: 'Applicability', width: 40 },
    { header: 'Proof of Compliance', width: 30 },
    { header: 'Effective Date', width: 14 },
    { header: 'Mapped Locations', width: 16 },
    { header: 'Active Status', width: 12 },
];

/**
 * The Browse list as an Excel file: the ticked compliances when ids are given, otherwise everything matching the filters.
 * "Mapped Locations" counts the company's active assignments of each compliance.
 */
export async function exportCompliances(actor: AuthUser, q: Parameters<typeof complianceWhere>[1], ids?: string[]) {
    const { orgId } = actor;
    const where = ids?.length ? { AND: [complianceWhere(orgId, { ...q, status: 'all' }), { id: { in: ids } }] } : complianceWhere(orgId, q);
    const [rows, org, me] = await Promise.all([
        prisma.compliance.findMany({
            where,
            include: {
                act: { select: { name: true, state: true, lawCategory: { select: { name: true } } } },
                rule: { select: { name: true } },
                nature: { select: { name: true } },
                type: { select: { name: true } },
                _count: { select: { schedules: { where: { orgId, isActive: true } } } },
            },
            orderBy: [{ act: { name: 'asc' } }, { title: 'asc' }],
            take: EXPORT_LIMIT + 1,
        }),
        prisma.organization.findUnique({ where: { id: orgId }, select: { name: true } }),
        prisma.user.findUnique({ where: { id: actor.id }, select: { name: true } }),
    ]);
    if (rows.length > EXPORT_LIMIT) {
        throw new HttpError(400, `More than ${EXPORT_LIMIT.toLocaleString('en-IN')} compliances match. Narrow the filters first.`);
    }

    const wb = new ExcelJS.Workbook();
    wb.creator = 'Compliance Platform';
    const ws = wb.addWorksheet('Compliances', { views: [{ state: 'frozen', ySplit: 4 }] });
    ws.columns = COLUMNS.map((c) => ({ width: c.width }));
    const now = new Date(Date.now() + 330 * 60_000).toISOString().replace('T', ' ').slice(0, 19);
    ws.addRow(['Organisation:', org?.name ?? '', 'Report Name:', 'Compliance Master']);
    ws.addRow(['Generated By:', me?.name ?? '', 'Report Generated On:', `${now} (India time)`]);
    ws.addRow([]);
    const head = ws.addRow(COLUMNS.map((c) => c.header));
    head.font = { bold: true };
    head.fill = { type: 'pattern', pattern: 'solid', fgColor: { argb: 'FFD9E1F2' } };
    for (const c of rows) {
        ws.addRow([
            c.code,
            safe(c.title),
            safe(c.description),
            safe(c.act.name),
            safe(c.rule?.name),
            c.act.state ?? 'Central',
            c.act.lawCategory.name,
            c.orgId ? 'Internal' : 'Statutory',
            c.nature?.name ?? '',
            c.type?.name ?? '',
            words(c.frequency),
            safe(dueRuleText(c)),
            c.periodBasis === 'FINANCIAL_YEAR' ? 'Financial' : 'Calendar',
            safe(c.form),
            safe(c.reference),
            words(c.risk),
            words(c.impact),
            words(c.attachment),
            safe(c.penalty),
            c.imprisonment ? 'Yes' : 'No',
            safe(c.applicability),
            safe(c.proofOfCompliance),
            c.effectiveDate ? toDateOnly(c.effectiveDate) : '',
            c._count.schedules,
            c.isActive ? 'Y' : 'N',
        ]);
    }
    ws.autoFilter = { from: { row: 4, column: 1 }, to: { row: 4, column: COLUMNS.length } };

    return {
        fileName: `Compliance_Master-${todayInIndia()}.xlsx`,
        buffer: Buffer.from(await wb.xlsx.writeBuffer()),
        count: rows.length,
    };
}